// node build-roads.mjs → ../roads.js
// The big roads of Bulgaria from OpenStreetMap (ODbL): motorways, trunk roads (first-class roads mostly) and primary roads,
// as SVG paths in map units, with the motorways' names (АМ „Тракия“…) and refs (A1…).
import fs from 'fs';

const REAL = JSON.parse(fs.readFileSync(new URL('../real-map.js', import.meta.url), 'utf8').replace(/^[\s\S]*?const REAL=/, '').replace(/;\s*$/, ''));
const P = ({ lon, lat }) => [(lon - REAL.lon0) * REAL.cx * REAL.k, (REAL.lat1 - lat) * REAL.k];
const r1 = (v) => Math.round(v * 10) / 10;
function simplify(p, tol) { // Douglas-Peucker
  if (p.length < 3) return p;
  const keep = new Uint8Array(p.length); keep[0] = keep[p.length - 1] = 1; const st = [[0, p.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1; const [ax, ay] = p[a], [bx, by] = p[b], dx = bx - ax, dy = by - ay, l = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) { const [x, y] = p[i]; let t = l ? ((x - ax) * dx + (y - ay) * dy) / l : 0; t = Math.max(0, Math.min(1, t)); const d = Math.hypot(x - ax - t * dx, y - ay - t * dy); if (d > md) { md = d; mi = i; } }
    if (md > tol) { keep[mi] = 1; st.push([a, mi], [mi, b]); }
  }
  return p.filter((_, i) => keep[i]);
}
const CLASS = { motorway: 'motorway', motorway_link: null, trunk: 'trunk', primary: 'primary' };
const paths = { motorway: [], trunk: [], primary: [] }, names = new Map();
for (const w of JSON.parse(fs.readFileSync(new URL('./data/roads.json', import.meta.url), 'utf8')).elements) {
  const c = CLASS[w.tags?.highway]; if (!c || !w.geometry) continue;
  const q = simplify(w.geometry.map(P), .4); if (q.length < 2) continue;
  paths[c].push('M' + q.map((p) => r1(p[0]) + ' ' + r1(p[1])).join('L'));
  if (c === 'motorway' && w.tags.ref) { const n = names.get(w.tags.ref) || { ref: w.tags.ref, n: w.tags.name || '', pts: 0 }; n.pts += q.length; if (!n.n && w.tags.name) n.n = w.tags.name; names.set(w.tags.ref, n); }
}
const ROADS = { motorway: paths.motorway.join(''), trunk: paths.trunk.join(''), primary: paths.primary.join(''), motorways: [...names.values()].map(({ ref, n }) => ({ ref, n })) };
const out = new URL('../roads.js', import.meta.url);
fs.writeFileSync(out, `/* generated by tools/build-roads.mjs from OpenStreetMap (ODbL): big roads of Bulgaria in map units */\nconst ROADS=${JSON.stringify(ROADS)};\n`);
console.log(`roads.js ${(fs.statSync(out).size / 1024).toFixed(0)} KB · motorways ${ROADS.motorways.map((m) => m.ref).join(', ')}`);

// node build-cities.mjs → ../cities.js
// The cities layer: Bulgaria's towns above 18 000 people (all 28 oblast centres among them) and the big cities around it,
// with population and coordinates from Wikidata. Sofia's and Varna's city districts are dropped (they are towns in Wikidata).
import fs from 'fs';

const UA = { 'User-Agent': 'cities-build/1.0', Accept: 'application/sparql-results+json' };
// answers are cached in data/ (fetch-data.sh does not refetch them): delete the file to ask Wikidata again
const cached = async (file, q) => { const f = new URL('./data/' + file, import.meta.url); if (fs.existsSync(f)) return JSON.parse(fs.readFileSync(f, 'utf8'));
  const b = await sparql(q); fs.writeFileSync(f, JSON.stringify(b)); return b; };
const sparql = async (q) => { // the public endpoint times out now and then: try a few times
  for (let i = 0; ; i++) {
    const r = await fetch('https://query.wikidata.org/sparql?query=' + encodeURIComponent(q), { headers: UA });
    if (r.ok) return (await r.json()).results.bindings;
    if (i === 3) throw new Error(`Wikidata ${r.status}`); await new Promise((ok) => setTimeout(ok, 5000 * (i + 1)));
  }
};
const pt = (wkt) => wkt.match(/Point\(([-\d.]+) ([-\d.]+)\)/).slice(1).map(Number);
const r4 = (v) => Math.round(v * 1e4) / 1e4;

// Bulgaria: towns with a population, their Bulgarian names, and whether they are an oblast's centre
const bg = await cached('wd-bg-towns.json', `SELECT ?c ?n ?pop ?coord ?obl WHERE {
  ?c wdt:P17 wd:Q219; wdt:P31/wdt:P279* wd:Q486972; wdt:P1082 ?pop; wdt:P625 ?coord.
  FILTER(?pop > 18000) ?c rdfs:label ?n FILTER(lang(?n)="bg")
  OPTIONAL { ?obl wdt:P36 ?c; wdt:P31 wd:Q209824 } }`);
// around it: the capitals and big cities in the map's frame (lon 15–36.5, lat 37–47), by their English names
const AROUND = ['Bucharest', 'Belgrade', 'Skopje', 'Athens', 'Istanbul', 'Ankara', 'Thessaloniki', 'Edirne', 'Constanța', 'Craiova',
  'Niš', 'Chișinău', 'Odesa', 'Tirana', 'Podgorica', 'Pristina', 'Sarajevo', 'Budapest', 'Bursa', 'İzmir', 'Novi Sad', 'Timișoara',
  'Cluj-Napoca', 'Iași', 'Brașov', 'Kayseri', 'Eskişehir', 'Konya', 'Sevastopol', 'Simferopol', 'Bari', 'Naples', 'Patras', 'Larissa', 'Galați', 'Ploiești'];
const near = await cached('wd-around.json', `SELECT ?c ?n ?en ?pop ?coord ?cap WHERE {
  VALUES ?en { ${AROUND.map((n) => JSON.stringify(n) + '@en').join(' ')} }
  ?c rdfs:label ?en; wdt:P1082 ?pop; wdt:P625 ?coord. FILTER(?pop > 100000)
  OPTIONAL { ?country wdt:P36 ?c; wdt:P31 wd:Q6256. BIND(true AS ?cap) }
  OPTIONAL { ?c rdfs:label ?n FILTER(lang(?n)="bg") } }`);
const inFrame = ([lon, lat]) => lon > 15 && lon < 36.5 && lat > 37 && lat < 47;
const byId = new Map();
for (const b of bg) {
  const id = b.c.value.split('/').pop(), o = byId.get(id) || { n: b.n.value, pop: 0, c: pt(b.coord.value).map(r4), bg: true, obl: false, q: id };
  o.pop = Math.max(o.pop, +b.pop.value); if (b.obl) o.obl = true; byId.set(id, o);
}
const biggest = new Map(); for (const b of near) if (inFrame(pt(b.coord.value)) && +b.pop.value > (biggest.get(b.en.value)?.pop.value ?? 0)) biggest.set(b.en.value, b);
for (const b of biggest.values()) {
  const id = b.c.value.split('/').pop(), o = byId.get(id) || { n: (b.n || b.en).value, pop: 0, c: pt(b.coord.value).map(r4), bg: false, cap: false, q: id };
  o.pop = Math.max(o.pop, +b.pop.value); if (b.cap) o.cap = true; byId.set(id, o);
}
let cities = [...byId.values()].sort((a, b) => b.pop - a.pop);
// a Bulgarian "town" within 6 km of a bigger one is a city district (Средец, Владислав Варненчик, Аспарухово…)
const km = (a, b) => Math.hypot((a[0] - b[0]) * 81.7, (a[1] - b[1]) * 111.2);
cities = cities.filter((c, i) => !c.bg || !cities.slice(0, i).some((d) => km(c.c, d.c) < 6));
// rank: 1 = Sofia and the capitals, 2 = big cities and oblast centres, 3 = the other towns (shown when zoomed in)
for (const c of cities) c.r = c.n === 'София' || c.cap ? 1 : c.obl || c.pop > 400000 ? 2 : 3;

const BG_NAMES = { 'Ploiești': 'Плоещ' }; // the few big cities Wikidata has no Bulgarian label for
for (const c of cities) c.n = BG_NAMES[c.n] || c.n;
const out = new URL('../cities.js', import.meta.url);
fs.writeFileSync(out, `/* generated by tools/build-cities.mjs from Wikidata (CC0): name, population, [lon, lat], r = rank (1 capitals, 2 oblast centres and big cities, 3 other towns) */\nconst CITIES=${JSON.stringify(cities.map(({ n, pop, c, bg, r }) => ({ n, pop, c, bg, r })))};\n`);
console.log(`cities.js · ${cities.filter((c) => c.bg).length} in Bulgaria (${cities.filter((c) => c.bg && c.r <= 2).length} rank 1–2), ${cities.filter((c) => !c.bg).length} around: ${cities.filter((c) => !c.bg).map((c) => c.n).join(', ')}`);
